# LOOPS (Estrutura de Repetição)
# É uma estrutura de controle que permite executar o mesmo bloco de código repetidas vezes, economizando tempo e reduzindo erros ao automatizar tarefas repetitivas.

# Tipos
# - FOR
# - WHILE

# FOR 
# É um loop de contagem ou iteração. Sabe quando o loop vai terminar, não depende de uma condição verdadeira ou falsa. Conta até um número específico ou "passeia" por uma lista.
# A palavra "iterar" significa passar por cada elemento de um conjunto, um por um, até chegar ao fim.

# WHILE (Enquanto) - Estrutura condicional
# É um loop baseado em condição. Repete um determinado trecho do programa enquanto ela é verdadeira. Repete até uma condição mudar. Não sabe quantas vezes será repetido.

# EXEMPLOS WHILE
# - Atualizar os dados do estoque enquanto o usuário ser administrador.
# - Passar por cada linha de uma planilha recuperando dados enquanto não chegar até o final dela.